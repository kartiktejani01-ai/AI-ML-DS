a = 10
b = 20

# relational op.= {==, <, >, <=, >=, !=, }
result = a == b
print(f"{result} = {a} == {b}")

result = a > b
print(f"{result} = {a} > {b}")

result = a < b
print(f"{result} = {a} < {b}")

result = a <= b
print(f"{result} = {a} <= {b}")

result = a >= b
print(f"{result} = {a} >= {b}")

result = a != b
print(f"{result} = {a} != {b}")
